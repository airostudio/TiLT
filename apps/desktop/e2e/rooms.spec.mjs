import { test, expect } from './harness.mjs'

test('rooms: both rooms and their systems are listed', async ({ page, app, shot }) => {
  await app()
  await page.waitForSelector('[data-testid=rooms]')
  expect((await page.textContent('[data-testid=room-home]')).includes('Home Arcade'))
  const home = await page.textContent('[data-testid=room-home]')
  const pin = await page.textContent('[data-testid=room-pinball]')
  for (const s of ['Amiga Studio', 'PlayStation 2', 'Intellivision']) expect(home.includes(s), `home room lists ${s}`)
  for (const s of ['MAME Arcade', 'TiLT Pinball']) expect(pin.includes(s), `pinball room lists ${s}`)
  await shot('rooms-home')
  await page.click('[data-testid=room-pinball]')
  await page.waitForSelector('[data-testid=system-mame]')
  const mame = await page.textContent('[data-testid=system-mame]')
  expect(mame.includes('Needs setup'), 'unconfigured external emulator is honest about needing setup')
  await shot('room-pinball')
})

test('rooms: external system setup, game list, favourites and launch', async ({ page, app, api, dir, shot }) => {
  const { writeFileSync, mkdirSync, chmodSync } = await import('node:fs')
  const path = await import('node:path')
  const games = path.join(dir, 'games')
  mkdirSync(games, { recursive: true })
  writeFileSync(path.join(games, 'Space Cadet.int'), 'x')
  writeFileSync(path.join(games, 'Astro.int'), 'x')
  writeFileSync(path.join(games, 'notes.txt'), 'x')
  const exe = path.join(dir, 'emu.sh')
  writeFileSync(exe, '#!/bin/sh\nsleep 20\n')
  chmodSync(exe, 0o755)
  await app('room/home/intellivision')
  await page.fill('input[placeholder="File path"]', exe)
  await page.fill('input[placeholder="Folder path"]', games)
  await page.click('text=Save settings')
  await page.waitForSelector('text=Astro')
  expect(!(await page.textContent('body')).includes('notes'), 'only matching file types are listed')
  await page.click('[aria-label="Add Astro to favourites"]')
  await page.waitForSelector('[aria-label="Remove Astro from favourites"]')
  await shot('system-games')
  await page.click('tr:has-text("Space Cadet") >> text=Play')
  await page.waitForSelector('text=Stop')
  const sys = await api('systems_list')
  expect(sys.find((s) => s.id === 'intellivision').running === true, 'launched process is tracked')
  await api('system_stop', { id: 'intellivision' })
})
