import { test, expect, fixtures, writeFile } from './harness.mjs'
import { renameSync, mkdirSync } from 'node:fs'
import path from 'node:path'

test('first run: wizard imports ROMs by content and attaches them to machines', async ({ page, app, api, dir, shot }) => {
  // misleading names on purpose: the version must come from the ROM itself
  const k13 = writeFile(dir, 'kick31.rom', fixtures.rom(34, 5))
  const k31 = writeFile(dir, 'kick13.rom', fixtures.rom(40, 68, 0x80000))
  const bad = writeFile(dir, 'broken.rom', Buffer.from([1, 2, 3, 4]))
  await app('amiga/dashboard')
  await page.waitForSelector('[data-testid=first-run-wizard]')
  expect((await page.textContent('body')).includes('does not include any Kickstart ROMs'), 'privacy / no-bundled-ROMs statement is shown')
  await shot('wizard-1-welcome')
  await page.click('text=Import my Kickstart ROMs')
  for (const f of [k13, k31, bad]) {
    await page.fill('input[aria-label="File path"]', f)
    await page.click('button:has-text("Import")')
    await page.waitForTimeout(150)
  }
  await page.waitForSelector('text=Use them in my machines')
  const body = await page.textContent('[data-testid=first-run-wizard]')
  expect(body.includes('Kickstart 1.3 (34.5)'), 'ROM named kick31 is detected as 1.3 from its content')
  expect(body.includes('Kickstart 3.1 (40.68)'), 'ROM named kick13 is detected as 3.1 from its content')
  await shot('wizard-2-imported')
  await page.click('text=Use them in my machines')
  await page.waitForSelector('text=Machines ready to start')
  await shot('wizard-3-done')
  const profiles = await api('profile_list')
  const roms = await api('rom_list')
  const byVer = (v) => roms.find((r) => r.info.exec_version === v).id
  expect(profiles.find((p) => p.id === 'preset-a500').rom_id === byVer(34), 'A500 got Kickstart 1.3')
  expect(profiles.find((p) => p.id === 'preset-a1200').rom_id === byVer(40), 'A1200 got the AGA-capable 3.1')
  expect(profiles.find((p) => p.id === 'preset-a4000_040').rom_id === byVer(40), 'A4000 got 3.1')
  expect(roms.length === 2, 'the corrupt ROM was rejected, not stored')
  await page.click('text=Go to the dashboard')
  await page.waitForSelector('[data-testid=current-machine]')
  await shot('dashboard-after-wizard')
})

test('dashboard: shows the machine, flags problems honestly and blocks start without a ROM', async ({ page, app, api, shot }) => {
  await api('rom_list')
  await app('amiga/dashboard')
  await page.click('text=Skip for now')
  await page.waitForSelector('[data-testid=current-machine]')
  const body = await page.textContent('body')
  expect(body.includes('Motorola 68EC020'), 'A1200 CPU shown')
  expect(body.includes('AGA'), 'chipset shown')
  expect(body.includes('2 MB'), 'chip RAM shown')
  const start = page.locator('button:has-text("Start")').first()
  expect(await start.isDisabled(), 'Start is disabled when the machine has no Kickstart')
  await page.selectOption('select', 'preset-a1200_040')
  expect((await page.textContent('body')).includes('Emulated 68040 accelerator'), 'accelerator described as an emulated configuration')
  expect(!(await page.textContent('body')).toLowerCase().includes('blizzard'), 'no physical board names are claimed')
  await shot('dashboard-a1200-040')
})

test('ROM library: duplicates, moved referenced ROM relink, protected removal', async ({ page, app, api, dir, shot }) => {
  const rom = writeFile(dir, 'k13.rom', fixtures.rom(34, 5))
  const dup = writeFile(dir, 'copy-of-k13.bin', fixtures.rom(34, 5))
  await app('amiga/roms')
  await page.getByLabel('Use the file where it is', { exact: false }).check().catch(async () => page.click('text=Use the file where it is'))
  await page.fill('input[aria-label="File path"]', rom)
  await page.click('button:has-text("Import")')
  await page.waitForSelector('[data-testid=rom-row]')
  expect((await page.textContent('[data-testid=ks-coverage]')).includes('✓ Kickstart 1.3'), 'coverage shows 1.3 present')
  await page.fill('input[aria-label="File path"]', dup)
  await page.click('button:has-text("Import")')
  await page.waitForSelector('text=Already in your library')
  // user moves the original
  mkdirSync(path.join(dir, 'moved'))
  renameSync(rom, path.join(dir, 'moved', 'k13.rom'))
  await page.reload()
  await page.waitForSelector('text=File moved')
  await shot('rom-library-moved')
  writeFile(path.join(dir, 'moved'), 'other.rom', fixtures.rom(37, 175, 0x80000))
  await page.click('button:has-text("Relink")')
  await page.fill('input[placeholder="File path"]', path.join(dir, 'moved', 'other.rom'))
  await page.click('.modal button:has-text("Relink")')
  await page.waitForSelector('.toast:has-text("different ROM")')
  await page.fill('input[placeholder="File path"]', path.join(dir, 'moved', 'k13.rom'))
  await page.click('.modal button:has-text("Relink")')
  await page.waitForSelector('text=Original location')
  // a machine using it blocks removal
  const [r] = await api('rom_list')
  const p = await api('profile_get', { id: 'preset-a500' })
  await api('profile_save', { profile: { ...p, rom_id: r.id } })
  await page.reload()
  await page.click('button[aria-label^="Remove"]')
  await page.click('.modal button:has-text("Remove")')
  await page.waitForSelector('text=is used by')
  expect((await api('rom_list')).length === 1, 'ROM still present after refused removal')
})
